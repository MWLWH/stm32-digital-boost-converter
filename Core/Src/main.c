void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc)
{
    Data(&eys);
    HAL_GPIO_TogglePin(user_led_GPIO_Port, user_led_Pin);
    eys.cnt++;
    if(eys.cnt > 5000)
    {
        can_data();
        eys.cnt = 0;
    }

    if(Mode != IDLE && Mode != Err)
    {
        // Switch between NO_LOAD and WITH_LOAD based on quiescent current threshold (0.5 A)
        if(eys.A > 0.5)
        {
            Mode = WITH_LOAD;
        }
        else
        {
            Mode = NO_LOAD;
        }

        if(eys.V_OUT > V_MAX || eys.A > A_MAX || (eys.EMA_V_IN < 24))
        {
            Mode = Err;
        }
    }

    switch(Mode)
    {
        case(IDLE):
            PWM_Stop(&eys);
            break;

        case(NO_LOAD):
            PI_NO_LOAD(&eys);

            if(eys.D <= MAX_D)
            {
                EYS_Soft_Start(&eys);
                if(!eys.soft_start_control)
                {
                    PWM_Change(&eys);
                }
            }
            break;

        case(WITH_LOAD):
            PI(&eys);
            PI_A(&eys);

            float duty_voltage = eys.PI_OUT;
            float duty_current = eys.PI_A_OUT;

            // Minimum-select arbitration for smooth Constant-Current / Constant-Voltage (CC/CV) crossover
            float target_D = (duty_current < duty_voltage) ? duty_current : duty_voltage;

            Slew_Rate_Limit(&eys, target_D);

            EYS_Soft_Start(&eys);
            if(!eys.soft_start_control)
            {
                PWM_Change(&eys);
            }
            break;

        case(Err):
            PWM_Stop(&eys);
            break;
    }
}

void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan_ptr)
{
    if (HAL_CAN_GetRxMessage(hcan_ptr, CAN_RX_FIFO0, &eys.RxHeader, eys.CAN.received_message) == HAL_OK)
    {
        if(eys.CAN.received_message[0] == 3)
        {
            eys.CAN.ecu_current_ref = 5;
        }
        else
        {
            eys.CAN.ecu_current_ref = eys.CAN.received_message[0];
        }
        eys.CAN.h2_ratio = eys.CAN.received_message[1];
        eys.CAN.cnt = 0;
        eys.ecu_flag = 1;
    }
}
